#!/usr/bin/env python3
"""Import/diff the native Figma number export; generate deterministic CSS. No API token."""
import argparse
import difflib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPORT = ROOT / 'design/figma/website-foundations.tokens.json'
HANDOFF = ROOT / 'design/handoff.json'
CSS = ROOT / 'assets/tokens.css'


def numbers(data, prefix=''):
    result = {}
    for name, value in data.items():
        if name.startswith('$'):
            continue
        path = f'{prefix}/{name}'.strip('/')
        if '$value' in value:
            number = value['$value']
            if value.get('$type') != 'number' or type(number) not in (int, float) or not 0 < number <= 4096:
                raise ValueError(f'Invalid numeric token: {path}')
            identity = value.get('$extensions', {}).get('com.figma.variableId')
            if not identity:
                raise ValueError(f'Missing Figma variable ID: {path}')
            result[path] = (number, identity)
        else:
            result.update(numbers(value, path))
    return result


def render(data, handoff):
    values = numbers(data)
    lines = ['/* Generated by scripts/design_tokens.py. Edit the design sources, then regenerate. */', ':root {']
    for name, (value, _) in sorted(values.items()):
        lines.append(f'  --{name.replace("/", "-")}: {value:g}px;')
    for name, value in handoff['colors'].items():
        if not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
            raise ValueError(f'Invalid color: {name}')
        lines.append(f'  --{name.replace("/", "-")}: {value.upper()};')
    lines.append('  --color-image-matte: #E4EBE7;')
    for name, value in handoff['typography'].items():
        if not isinstance(value, dict):
            continue
        css_name = name.replace('/', '-')
        lines += [f'  --{css_name}-size: {value["fontSize"]}px;', f'  --{css_name}-line: {value["lineHeight"]}px;']
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail when committed CSS differs from design sources')
    parser.add_argument('--import-export', type=Path, help='Validate, diff, and import a new native number export')
    parser.add_argument('--allow-schema-change', action='store_true', help='Explicitly accept removed/renamed tokens or changed variable IDs')
    args = parser.parse_args()
    data = json.loads(EXPORT.read_text())
    if args.import_export:
        if args.check:
            parser.error('--check cannot import')
        candidate = json.loads(args.import_export.read_text())
        before, after = numbers(data), numbers(candidate)
        changed_identity = set(before) != set(after) or any(before[k][1] != after[k][1] for k in before.keys() & after.keys())
        if changed_identity and not args.allow_schema_change:
            parser.error('Token names/IDs changed. Review Figma mappings and CSS references; repeat with --allow-schema-change only after review.')
        for key in sorted(before.keys() | after.keys()):
            if before.get(key) != after.get(key):
                print(f'{key}: {before.get(key)} -> {after.get(key)}')
        data = candidate
        # Validate CSS before writing either file.
    output = render(data, json.loads(HANDOFF.read_text()))
    if args.check:
        current = CSS.read_text() if CSS.exists() else ''
        if current != output:
            print(''.join(difflib.unified_diff(current.splitlines(True), output.splitlines(True), fromfile='committed CSS', tofile='design sources')))
            raise SystemExit(1)
        print('Design tokens and generated CSS match.')
    else:
        if args.import_export:
            EXPORT.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
        CSS.write_text(output)
        print('Generated assets/tokens.css')


if __name__ == '__main__':
    main()
